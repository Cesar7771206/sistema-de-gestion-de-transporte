    public void cargarCombos() {
        cboTractor.removeAllItems();
        cboCarreta.removeAllItems();

        cboCarreta.addItem("(Sin Carreta)");

        for (Tractor t : GestorEquipos.getTractores()) {
            boolean enUso = false;
            for (UnidadTransporte u : GestorEquipos.getUnidades()) {
                if (u.getTractor() != null && u.getTractor().getPlaca().equalsIgnoreCase(t.getPlaca())) {
                    enUso = true;
                    break;
                }
            }
            if (!enUso) {
                cboTractor.addItem(t.getPlaca() + " - " + t.getMarca());
            }
        }

        for (Carreta c : GestorEquipos.getCarretas()) {
            boolean enUso = false;
            for (UnidadTransporte u : GestorEquipos.getUnidades()) {
                if (u.getCarreta() != null && u.getCarreta().getPlaca().equalsIgnoreCase(c.getPlaca())) {
                    enUso = true;
                    break;
                }
            }
            if (!enUso) {
                cboCarreta.addItem(c.getPlaca() + " - " + c.getMarca());
            }
        }
    }

    public void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblUnidades.getModel();
        modelo.setRowCount(0);

        List<UnidadTransporte> unidades = GestorEquipos.getUnidades();
        int index = 1;
        for (UnidadTransporte u : unidades) {
            String tractorPlaca = u.getTractor() != null ? u.getTractor().getPlaca() : "-";
            String tractorMarca = u.getTractor() != null ? u.getTractor().getMarca() : "-";
            String carretaPlaca = u.getCarreta() != null ? u.getCarreta().getPlaca() : "(Sin Carreta)";
            String carretaMarca = u.getCarreta() != null ? u.getCarreta().getMarca() : "-";
            String estado = u.getEstado() != null ? u.getEstado().name() : "DISPONIBLE";

            modelo.addRow(new Object[]{
                index++,
                tractorPlaca,
                tractorMarca,
                carretaPlaca,
                carretaMarca,
                estado
            });
        }

        lblContador.setText("Unidades registradas: " + unidades.size() + " / 7 (Límite máximo de 7 unidades)");
    }

